/**
 * Generates app/moods.css from lib/moods.ts so there is exactly one source of
 * truth for the 10 moods. Runs automatically before `dev` and `build`.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { allMoodsCss, DEFAULT_MOOD, getMood, moodToCss } from "../lib/moods";

const def = getMood(DEFAULT_MOOD);
const css = `/* AUTO-GENERATED by scripts/build-moods.ts from lib/moods.ts — do not edit. */
:root{color-scheme:${def.scheme};${moodToCss(def)}}
${allMoodsCss()}
`;

writeFileSync(join(process.cwd(), "app", "moods.css"), css);
console.log("moods.css written (" + css.length + " bytes)");
